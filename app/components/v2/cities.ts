// one service in one city: everything that changes per service (never copied from the service page: duplicate content)
export type CityService = {
  metaTitle: string;
  metaDescription: string;
  heroMuted: string; // first (grey) line of the hero title
  heroTitle: string; // second line
  heroLine: string; // one sentence under the title
  clients: string[]; // case slugs, in display order
  clientPlaces?: Record<string, string>; // label override per client, e.g. SG "Mannheim · 8 Standorte"; otherwise the client's own place
  ringExclude?: string[]; // mockups to leave out of the hero ring on this page (Google Ads: never Herkules)
  clientsTitle: string;
  clientsText: string;
  // explainer under the hero: <prefix>-1080.mp4, -9x16.mp4, -poster.jpg, -poster-9x16.jpg, .de.vtt; transcript + facts for the VideoObject schema
  video?: { prefix: string; title: string; description: string; seconds: number; uploadDate: string; transcript: string };
  // mode "chat": the phone shows an AI chat (question, three named businesses, yours missing) instead of a Google search;
  // mode "insta": two Instagram profiles, yours empty, the other full of work
  problem: { strong: string; muted: string; text: string; query: string; chips: [string, string]; mode?: "search" | "chat" | "insta" };
  stepsTitle: string;
  steps: Array<{ tab: string; title: string; body: string; art: StepArtKind }>;
  // price section: web = the Webdesign page's package section; the others = PackageSection with this tier
  tier?: string;
  packageNote: string;
  faqs: CityFaq[];
};

// a city: the parts every service page shares (hero ring, map, districts) plus one entry per service
export type CityData = {
  slug: string;
  name: string;
  showcase: string[]; // hero ring mockups (/assets/v2/mockups/<name>.webp); Halyl 11 Nov 2026: all our websites, not only this city's
  landmark?: "wasserturm" | "frankfurt" | "heidelberg" | "berlin" | "hamburg" | "muenchen" | "koeln" | "stuttgart" | "duesseldorf"; // drawn landmark in the middle of the hero ring
  districts: string[];
  spots: [string, string, string]; // three districts the drawings use (search result, page tree, chat answer), so each city's drawings differ
  // the example trade in the drawings: search term, the page it finds, three service pages, the guide article's title
  trade: { term: string; page: string; pages: [string, string, string]; article: string };
  nearby: string[];
  localText: string;
  pages: Partial<Record<ServiceKey, CityService>>;
};

// what one page renders: the city's shared parts with one service's content
export type City = Omit<CityData, "pages"> & CityService & { service: ServiceKey };

