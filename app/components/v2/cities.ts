export const cityBySlug = (slug?: string) => CITIES.find((c) => c.slug === slug);

// one page: the city with one service's content, or undefined if that page does not exist
export function cityPage(citySlug?: string, serviceSlug?: string): City | undefined {
  const city = cityBySlug(citySlug);
  const service = serviceBySlug(serviceSlug);
  const page = city && service ? city.pages[service] : undefined;
  if (!city || !service || !page) return undefined;
  const { pages: _pages, ...shared } = city;
  return { ...shared, ...page, service };
}

